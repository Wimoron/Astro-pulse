def hms(s):
    h, m, sec = [float(x) for x in s.split(':')]
    return (h + m / 60 + sec / 3600) * 15
def dms(s):
    sign = -1 if s.startswith('-') else 1
    parts = [float(x) for x in s.lstrip('+-').split(':')]
    return sign * (parts[0] + parts[1] / 60)
